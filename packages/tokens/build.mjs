#!/usr/bin/env node
/**
 * Extracts the design tokens that are byte-identical in the two shipped
 * stylesheets and writes packages/tokens/tokens.json.
 *
 * The apps keep serving their own compiled CSS (parity requires the original
 * bytes). This package is the canonical record of the shared scale, and the
 * only place a future hand-written rule should read tokens from.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repo = join(here, '..', '..')
const web = readFileSync(join(repo, 'apps/web/src/styles/base.css'), 'utf8')
const legal = readFileSync(join(repo, 'apps/legal/public/_astro/Layout.CdK3j_XA.css'), 'utf8')

function declarations(css) {
  const map = new Map()
  for (const m of css.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;}]+)/g)) {
    const name = m[1]
    const value = m[2].trim()
    if (!map.has(name)) map.set(name, new Set())
    map.get(name).add(value)
  }
  return map
}

const a = declarations(web)
const b = declarations(legal)
const shared = {}
for (const [name, values] of a) {
  const other = b.get(name)
  if (!other) continue
  const common = [...values].filter((v) => other.has(v))
  if (common.length) shared[name] = common.length === 1 ? common[0] : common
}

const sorted = Object.fromEntries(Object.entries(shared).sort(([x], [y]) => x.localeCompare(y)))
writeFileSync(join(here, 'tokens.json'), JSON.stringify(sorted, null, 2))
writeFileSync(
  join(here, 'src', 'index.ts'),
  `/** Generated by build.mjs — design tokens verified identical in both origins. */\nexport const tokens = ${JSON.stringify(sorted, null, 2)} as const\n\nexport type TokenName = keyof typeof tokens\n`,
)
console.log(`shared token declarations: ${Object.keys(sorted).length}`)
